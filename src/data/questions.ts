export const questions: Question[] = Object.entries(banks).flatMap(
  ([category, texts]) =>
    texts.map((text, i) => ({
      id: `${category}-${i + 1}`,
      category: category as Question["category"],
      text,
    })),
);
export function readSavedQuestions(): Question[] {
  try {
    const stored: unknown = JSON.parse(
      localStorage.getItem("eleven-custom") || "[]",
    );
    if (!Array.isArray(stored)) return [];
    return stored
      .map((q) => questionSchema.safeParse(q))
      .filter((q) => q.success && q.data.category === "custom")
      .map((q) => q.data!)
      .slice(0, 200);
  } catch {
    return [];
  }
}
